#!/usr/bin/env python3
"""Generate Poseidon parameters over the P-256 base field (= T-256 scalar field).

Port of the Poseidon reference `generate_parameters_grain.sage` and
`calc_round_numbers.py` (https://extgit.iaik.tugraz.at/krypto/hadeshash):
- round numbers: 128-bit security, with the reference's +2 R_F / +7.5% R_P margin
  and the 2023/537 Groebner bound;
- round constants: Grain LFSR, rejection-sampled below p;
- MDS: Cauchy matrix over Grain-sampled distinct elements.

The reference additionally runs invariant-subspace checks on the MDS matrix and
regenerates it if they fail; those are not ported. For t = 3 a Cauchy matrix
almost never fails them, but this has to be re-checked before production use.

Why not the usual x^5: gcd(5, p-1) = 5 for the P-256 prime, so x^5 is not a
permutation. x^7 is the smallest valid exponent (gcd(3, p-1) = 3 too).

Usage: python3 poseidon_params.py > ../src/poseidon_constants.rs
"""
import math

P = 2**256 - 2**224 + 2**192 + 2**96 - 1
N_BITS = 256
T = 3
ALPHA = 7
M = 128  # security level

assert math.gcd(ALPHA, P - 1) == 1


# --- round numbers (calc_round_numbers.py) ---

def log_binom2(n, k):
    return (math.lgamma(n + 1) - math.lgamma(k + 1) - math.lgamma(n - k + 1)) / math.log(2)


def sat_inequiv_alpha(p, t, R_F, R_P, alpha, M):
    n = N_BITS
    logp = math.log2(p)
    R_F_1 = 6 if M <= (math.floor(logp - ((alpha - 1) / 2.0))) * (t + 1) else 10
    R_F_2 = 1 + math.ceil(math.log(2, alpha) * min(M, n)) + math.ceil(math.log(t, alpha)) - R_P
    R_F_3 = (math.log(2, alpha) * min(M, logp)) - R_P
    R_F_4 = t - 1 + math.log(2, alpha) * min(M / float(t + 1), logp / 2.0) - R_P
    R_F_5 = (t - 2 + (M / float(2 * math.log(alpha, 2))) - R_P) / float(t - 1)
    R_F_max = max(math.ceil(R_F_1), math.ceil(R_F_2), math.ceil(R_F_3), math.ceil(R_F_4), math.ceil(R_F_5))
    r_temp = math.floor(t / 3.0)
    over = (R_F - 1) * t + R_P + r_temp + r_temp * (R_F / 2.0) + R_P + alpha
    under = r_temp * (R_F / 2.0) + R_P + alpha
    cost_gb4 = math.ceil(2 * log_binom2(over, under))
    return R_F >= R_F_max and cost_gb4 >= M


def round_numbers():
    best = None
    for R_P in range(1, 500):
        for R_F in range(4, 100, 2):
            if sat_inequiv_alpha(P, T, R_F, R_P, ALPHA, M):
                cost = T * R_F + R_P
                if best is None or cost < best[0]:
                    best = (cost, R_F, R_P)
                break
    _, R_F, R_P = best
    # The reference margin is +2 R_F and +7.5% R_P. This port reproduces the
    # circomlib BN254 constants exactly but lands one partial round under the
    # published x5_254_3 R_P (56 vs 57), so add 2 extra partial rounds to stay
    # on the conservative side.
    return R_F + 2, int(math.ceil(R_P * 1.075)) + 2


R_F, R_P = round_numbers()


# --- Grain LFSR (generate_parameters_grain.sage) ---

def grain_bits():
    init = [0, 1]  # field: prime
    init += [0, 0, 0, 0]  # sbox: x^alpha
    init += [int(b) for b in format(N_BITS, '012b')]
    init += [int(b) for b in format(T, '012b')]
    init += [int(b) for b in format(R_F, '010b')]
    init += [int(b) for b in format(R_P, '010b')]
    init += [1] * 30
    seq = init

    def step():
        nb = seq[62] ^ seq[51] ^ seq[38] ^ seq[23] ^ seq[13] ^ seq[0]
        seq.pop(0)
        seq.append(nb)
        return nb

    for _ in range(160):
        step()
    while True:
        nb = step()
        while nb == 0:
            step()
            nb = step()
        yield step()


GRAIN = grain_bits()


def grain_field():
    while True:
        v = 0
        for _ in range(N_BITS):
            v = (v << 1) | next(GRAIN)
        if v < P:
            return v


round_constants = [grain_field() for _ in range((R_F + R_P) * T)]

while True:
    xs_ys = [grain_field() for _ in range(2 * T)]
    if len(set(xs_ys)) == 2 * T:
        break
xs, ys = xs_ys[:T], xs_ys[T:]
mds = [[pow((xs[i] + ys[j]) % P, P - 2, P) for j in range(T)] for i in range(T)]


def h(v):
    return f'"0x{v:064x}"'


print('// Generated by vega/core/scripts/poseidon_params.py; do not edit.')
print(f'// Poseidon over the P-256 base field: t = {T}, alpha = {ALPHA}, R_F = {R_F}, R_P = {R_P}.')
print(f'pub const T: usize = {T};')
print(f'pub const ALPHA: u64 = {ALPHA};')
print(f'pub const R_F: usize = {R_F};')
print(f'pub const R_P: usize = {R_P};')
print(f'pub const ROUND_CONSTANTS: [&str; {len(round_constants)}] = [')
for c in round_constants:
    print(f'  {h(c)},')
print('];')
print(f'pub const MDS: [[&str; {T}]; {T}] = [')
for row in mds:
    print('  [' + ', '.join(h(v) for v in row) + '],')
print('];')

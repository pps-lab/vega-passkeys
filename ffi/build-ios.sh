#!/bin/sh
# Builds the Vega prover for iOS as a local Swift Package:
#   vega/ffi/out/PopVega/
#     Package.swift
#     PopVegaFFI.xcframework       (device arm64 + simulator arm64 static libs, C header, modulemap)
#     Sources/PopVega/pop_vega_ffi.swift   (UniFFI-generated Swift API)
# Add it to Xcode via File → Add Package Dependencies… → Add Local…
#
# Needs Xcode and: rustup target add aarch64-apple-ios aarch64-apple-ios-sim
set -eu
cd "$(dirname "$0")/.."            # vega/
ROOT=$(pwd)
OUT="$ROOT/ffi/out"
PKG="$OUT/PopVega"
export IPHONEOS_DEPLOYMENT_TARGET=${IPHONEOS_DEPLOYMENT_TARGET:-16.0}

./scripts/fetch-vega-prover.sh

echo "== building static libraries"
for target in aarch64-apple-ios aarch64-apple-ios-sim; do
  cargo build --release -p pop-vega-ffi --lib --target "$target"
done

echo "== generating Swift bindings"
cargo build --release -p pop-vega-ffi --lib            # host cdylib, read by uniffi-bindgen
rm -rf "$OUT/bindings" && mkdir -p "$OUT/bindings"
cargo run --release -q -p pop-vega-ffi --features cli --bin uniffi-bindgen -- \
  generate --library "$ROOT/target/release/libpop_vega_ffi.dylib" --language swift --out-dir "$OUT/bindings"

echo "== assembling XCFramework"
HEADERS="$OUT/headers"
rm -rf "$HEADERS" && mkdir -p "$HEADERS"
cp "$OUT/bindings/pop_vega_ffiFFI.h" "$HEADERS/"
cp "$OUT/bindings/pop_vega_ffiFFI.modulemap" "$HEADERS/module.modulemap"

rm -rf "$PKG" && mkdir -p "$PKG/Sources/PopVega"
xcodebuild -create-xcframework \
  -library "$ROOT/target/aarch64-apple-ios/release/libpop_vega_ffi.a" -headers "$HEADERS" \
  -library "$ROOT/target/aarch64-apple-ios-sim/release/libpop_vega_ffi.a" -headers "$HEADERS" \
  -output "$PKG/PopVegaFFI.xcframework" > /dev/null
cp "$OUT/bindings/pop_vega_ffi.swift" "$PKG/Sources/PopVega/"

cat > "$PKG/Package.swift" <<'SWIFT'
// swift-tools-version:5.9
// Generated by vega/ffi/build-ios.sh — do not edit.
import PackageDescription

let package = Package(
  name: "PopVega",
  platforms: [.iOS(.v16)],
  products: [.library(name: "PopVega", targets: ["PopVega"])],
  targets: [
    .binaryTarget(name: "pop_vega_ffiFFI", path: "PopVegaFFI.xcframework"),
    .target(name: "PopVega", dependencies: ["pop_vega_ffiFFI"], path: "Sources/PopVega"),
  ]
)
SWIFT

echo "== done: $PKG"
du -sh "$PKG/PopVegaFFI.xcframework"/*/libpop_vega_ffi.a
